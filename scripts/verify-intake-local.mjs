// Explicitly local integration exercise. Leaves clearly named test data in local D1 only.
import assert from "node:assert/strict";
import { randomUUID } from "node:crypto";
const base = "http://localhost:5173";
async function api(path, method = "GET", body, expected = 200) {
  const r = await fetch(base + path, { method, ...(body ? { headers: { "content-type": "application/json" }, body: JSON.stringify(body) } : {}) });
  const d = await r.json();
  assert.ok((Array.isArray(expected) ? expected : [expected]).includes(r.status), `${method} ${path}: expected ${expected}, got ${r.status}: ${JSON.stringify(d)}`);
  return d;
}
const suffix = randomUUID();
const input = { requestKey: randomUUID(), companyName: `Local Intake QA ${suffix}`, contactName: "Local QA Contact", email: `intake-${suffix}@example.invalid`, source: "website", summary: "Local-only inquiry test", owner: "QA operator", nextAction: "Schedule discovery", followUpDate: "2026-09-15" };
const created = await api("/api/inquiries", "POST", input, 201);
const accountId = created.inquiry.accountId;
const detailPath = `/api/clients/${accountId}`;
assert.equal((await api("/api/inquiries", "POST", input)).inquiry.id, created.inquiry.id, "retry is idempotent");
await api("/api/inquiries", "POST", { ...input, requestKey: randomUUID() }, 409);
await api("/api/inquiries", "POST", { ...input, requestKey: randomUUID(), companyName: "A different company" }, 409);
await api("/api/inquiries", "POST", { ...input, requestKey: randomUUID(), email: "", phone: "" }, 400);
let detail = await api(detailPath);
assert.equal(detail.client.relationshipType, "prospect");
assert.equal(detail.client.onboardingStatus, "not_started");
assert.equal(detail.tasks.length, 0);
let relationship = await api(detailPath + "/relationship");
assert.equal(relationship.contact.marketingStatus, "unknown");
assert.equal(relationship.account.relationshipNextAction, "Schedule discovery");
const update = { relationshipOwner: "QA operator", relationshipNextAction: "Review quote", followUpDate: "2026-09-16", salesStage: "won", marketingStatus: "subscribed", marketingEvidence: "" };
await api(detailPath + "/relationship", "PATCH", update, 400);
relationship = await api(detailPath + "/relationship", "PATCH", { ...update, marketingEvidence: "Local test opt-in only, 2026-09-06" });
assert.equal(relationship.account.relationshipType, "client");
detail = await api(detailPath);
assert.equal(detail.client.onboardingStatus, "not_started", "winning does not start delivery");
assert.equal((await api(detailPath + "/services")).services.length, 0, "winning creates no commercial order");
const second = await api("/api/inquiries", "POST", { ...input, requestKey: randomUUID(), accountId, contactName: "Must not overwrite canonical contact", source: "phone", summary: "Local callback" }, 201);
assert.equal(second.contactReused, true);
relationship = await api(detailPath + "/relationship");
assert.equal(relationship.contact.displayName, input.contactName);
assert.equal(relationship.contact.marketingStatus, "subscribed");
const followup = { id: created.inquiry.id, status: "closed", owner: "QA", nextAction: "", followUpDate: "", resolution: "" };
await api("/api/inquiries", "PATCH", followup, 400);
await api("/api/inquiries", "PATCH", { ...followup, resolution: "Local test completed" });
const inbox = await api(`/api/inquiries?accountId=${accountId}`);
assert.equal(inbox.inquiries.length, 2);
assert.equal(inbox.inquiries.find((i) => i.id === created.inquiry.id).status, "closed");
assert.ok((await api(detailPath)).activity.some((a) => a.action === "inquiry.updated"));
const internal = await api("/api/organization", "POST", undefined, [200, 201]);
assert.equal((await api("/api/organization", "POST")).accountId, internal.accountId);
await api("/api/inquiries", "POST", { ...input, requestKey: randomUUID(), accountId: internal.accountId }, 400);
await api(`/api/clients/${internal.accountId}/relationship`, "PATCH", { ...update, marketingStatus: "unknown" }, 400);
const internalDetail = await api(`/api/clients/${internal.accountId}`);
assert.equal(internalDetail.client.organizationKind, "internal");
console.log("PASS: saved inquiry → deduplication → contact reuse → follow-up → client relationship; no implicit onboarding/order/marketing; internal profile protected.");
